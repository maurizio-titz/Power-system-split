def summarize_special_carriers(n, carriers=("load", "art_load"), threshold=1e-6):
    """
    Summarize generation from special carriers (e.g. loadshedding, art_load)
    relative to total generation in the network.

    Parameters
    ----------
    n : pypsa.Network
        Solved PyPSA network.
    carriers : iterable of str
        Carrier names to summarize.
    threshold : float
        Dispatch above this value (in MW) counts as "active" for the
        occurrence count. Guards against floating point noise around 0.

    Returns
    -------
    pd.DataFrame indexed by carrier with columns:
        - generation_mwh: total energy produced by that carrier
        - share_of_total_generation: fraction of total system generation
        - n_snapshots_active: number of snapshots with dispatch > threshold
        - share_of_snapshots: fraction of all snapshots active
    """
    weights = n.snapshot_weightings.generators

    # --- total generation across the whole network (all generators) ---
    gen_p = n.generators_t.p
    total_generation_mwh = (gen_p.mul(weights, axis=0)).sum().sum()

    n_snapshots = len(n.snapshots)

    rows = {}
    print(carriers)
    for carrier in carriers:
        gens = n.generators.index[n.generators.carrier == carrier]

        if len(gens) == 0:
            # carrier not modeled as generators -> check links as fallback
            links = n.links.index[n.links.carrier == carrier] if "carrier" in n.links else []
            if len(links) > 0:
                p = n.links_t.p0[links]
            else:
                rows[carrier] = {
                    "generation_mwh": 0.0,
                    "share_of_total_generation": 0.0,
                    "n_snapshots_active": 0,
                    "share_of_snapshots": 0.0,
                }
                continue
        else:
            p = gen_p[gens]

        energy_per_snapshot = p.sum(axis=1)  # MW summed over units of this carrier
        generation_mwh = (energy_per_snapshot * weights).sum()

        active_mask = energy_per_snapshot.abs() > threshold
        n_active = int(active_mask.sum())

        rows[carrier] = {
            "generation_mwh": generation_mwh,
            "share_of_total_generation": (
                generation_mwh / total_generation_mwh if total_generation_mwh else 0.0
            ),
            "n_snapshots_active": n_active,
            "share_of_snapshots": n_active / n_snapshots if n_snapshots else 0.0,
        }

    return pd.DataFrame(rows).T


def consolidate_carrier(carrier):
    if carrier.startswith("solar"):
        return "solar"
    elif carrier in ["onwind", "offwind-ac", "offwind-dc", "offwind-float"]:
        return "wind"
    else:
        return carrier


