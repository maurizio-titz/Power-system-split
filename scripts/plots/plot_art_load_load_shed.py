n_nodes = 600


def plot_art_load_load_shed():
    co2ls = get_co2_levels(n_nodes)
    networks = {
        co2l: data_handling.load_pypsa_network(
            n_nodes=600, co2lvl=co2l, use_sclopf=True
        )
        for co2l in co2ls
    }

    setup_matplotlib_style()

    # consistent colors across all panels
    COLORS = {
        "load shedding": "#d62728",  # red
        "art_load": "#1f77b4",       # blue
    }

    fig, axes = plt.subplots(
        2, 4, figsize=(8 * 2, 10), sharey=True, sharex=False
    )
    axes = axes.flatten()

    if len(co2ls) == 1:
        axes = [axes]  # ensure iterable when there's only one co2 level

    for i, (ax, level) in enumerate(zip(axes, co2ls)):
        network_lvl = networks[level]

        time_data = (
            network_lvl.generators_t.p.mul(network_lvl.generators.sign)
            .T.groupby(network_lvl.generators["carrier"])
            .sum()
        )
        load = time_data.sum()

        load_shed_share = 100 * time_data.loc["load"] / load
        art_load_share = 100 * time_data.loc["art_load"].mul(-1) / load

        ax.plot(
            load_shed_share.index, load_shed_share,
            label="load shedding", color=COLORS["load shedding"], linewidth=1.2,
        )
        ax.plot(
            art_load_share.index, art_load_share,
            label="art_load", color=COLORS["art_load"], linewidth=1.2,
        )

        ax.set_ylim(bottom=0, top=0.5)
        ax.yaxis.set_major_formatter(PercentFormatter(xmax=100, decimals=1))

        ax.set_title(f"CO2 level: {level}", fontsize=SUBTITLE_FONTSIZE)
        ax.set_xlabel("Date", fontsize=AXIS_LABEL_FONTSIZE)
        ax.tick_params(axis="both", labelsize=TICK_LABEL_FONTSIZE)

        ax.xaxis.set_major_locator(mdates.AutoDateLocator())
        ax.xaxis.set_major_formatter(mdates.DateFormatter("%b"))

        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        ax.grid(True, alpha=0.3, linewidth=0.5)

    for row_start in (0, 4):
        axes[row_start].set_ylabel("Share of load [\%]", fontsize=AXIS_LABEL_FONTSIZE)

    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(
        handles, labels,
        loc="upper center", ncol=2, bbox_to_anchor=(0.5, 1.02),
        fontsize=LEGEND_FONTSIZE, frameon=False,
    )

    fig.tight_layout()
    save_figure(fig, save_path, "load_shedd_art_load_plot")
    plt.show()


if __name__ == "__main__":
    plot_art_load_load_shed()